"""Equal-budget hyperparameter search (protocol section 5).

    python scripts/tune.py generate                 # -> configs/exp/tune_<method>_<task>.yaml for all
    python scripts/tune.py generate pets ant        # one (method, task)
    python scripts/tune.py report results/rtx4090   # -> configs/tuned/*.yaml + analysis/tuning_budget.*

Search: seeded random search over configs/tuning/<method>.yaml (no extra dependency). Trial 0 is the
default config. Budget (trials, cap, seed) comes from configs/tuning/budget.yaml and is the same for
every method.

Objective (lower is better): wall-clock seconds until the run holds tau (two consecutive log rows,
the same rule as the analysis). An unsolved trial scores cap * (2 - clip(final / tau, 0, 1)), so it
always ranks behind every solved trial but still by how close it got.
"""

from __future__ import annotations

import argparse
import json
import math
import random
import shlex
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CFG = ROOT / "configs"


def _sample(spec: dict, rng: random.Random, drawn: dict):
    if "choice" in spec:
        return rng.choice(spec["choice"])
    if "uniform" in spec:
        lo, hi = spec["uniform"]
        return round(rng.uniform(lo, hi), 4)
    if "loguniform" in spec:
        lo, hi = spec["loguniform"]
        return float(f"{math.exp(rng.uniform(math.log(lo), math.log(hi))):.3g}")
    if "same_as" in spec:
        return drawn[spec["same_as"]]
    raise ValueError(f"unknown search spec {spec}")


def _fmt(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (list, dict)):
        return json.dumps(v, separators=(",", ":"))
    return str(v)


def trials_for(method: str, task: str, budget: dict) -> tuple[dict, list[dict]]:
    space_file = yaml.safe_load((CFG / "tuning" / f"{method}.yaml").read_text())
    space = {**space_file["space"], **(space_file.get("space_overrides", {}).get(task) or {})}
    fixed = (space_file.get("fixed") or {}).get(task) or {}
    rng = random.Random(f"{budget['sampler_seed']}-{method}-{task}")
    trials = [{}]  # trial 0 = defaults
    for _ in range(budget["trials"] - 1):
        drawn: dict = {}
        for k, spec in space.items():  # dict order: same_as refers to an earlier key
            drawn[k] = _sample(spec, rng, drawn)
        trials.append(drawn)
    return {"algo_file": space_file["algo_file"], "fixed": fixed, "space": space}, trials


def generate(methods, tasks, budget):
    for method in methods:
        for task in tasks:
            meta, trials = trials_for(method, task, budget)
            exp = f"tune_{method}_{task}"
            cap = budget["max_wall_s"][task]
            jobs = []
            for i, ov in enumerate(trials):
                args = {"algo": meta["algo_file"], "task": task, "seed": budget["seed"], "run.exp": exp,
                        "run.run_id": f"trial_{i:02d}", "algo.max_wall_s": cap,
                        "run.stop_at_tau": budget.get("stop_at_tau", True), **meta["fixed"], **ov}
                cmd = "python scripts/train.py " + " ".join(shlex.quote(f"{k}={_fmt(v)}") for k, v in args.items())
                jobs.append({"name": f"trial_{i:02d}", "cmd": cmd, "overrides": ov,
                             "timeout_min": int(cap / 60) + 15, "allow_fail": True})
            spec = {"name": exp, "timeout_min": int(cap / 60) + 15,
                    "tuning": {"method": method, "task": task, "algo_file": meta["algo_file"], "budget": budget, "space": meta["space"], "fixed": meta["fixed"]},
                    "jobs": jobs}
            out = CFG / "exp" / f"{exp}.yaml"
            out.write_text("# GENERATED by scripts/tune.py generate - do not edit; regenerate instead.\n"
                           + yaml.safe_dump(spec, sort_keys=False, width=200))
            print(f"wrote {out.relative_to(ROOT)} ({len(jobs)} trials, cap {cap}s)")


# ---------------------------------------------------------------------------------------------- report
def _rows(run_dir: Path) -> list[dict]:
    f = run_dir / "metrics.jsonl"
    return [json.loads(l) for l in open(f) if l.strip()] if f.exists() else []


def objective(rows: list[dict], tau: float, cap: float) -> tuple[float, bool, float | None]:
    r = [x for x in rows if x.get("reward_mean") is not None]
    for a, b in zip(r, r[1:]):
        if a["reward_mean"] >= tau and b["reward_mean"] >= tau:
            return a["wall_s"], True, a["reward_mean"]
    final = sum(x["reward_mean"] for x in r[-5:]) / len(r[-5:]) if r else None
    frac = 0.0 if final is None else min(1.0, max(0.0, final / tau))
    return cap * (2.0 - frac), False, final


def report(gpu_dir: Path, budget: dict, paper: str | None):
    thresholds = yaml.safe_load((CFG / "thresholds.yaml").read_text())
    table = []
    for method in budget["methods"]:
        for task in budget["tasks"]:
            exp = f"tune_{method}_{task}"
            spec_f = CFG / "exp" / f"{exp}.yaml"
            exp_dir = gpu_dir / exp
            if not spec_f.exists() or not exp_dir.exists():
                print(f"skip {exp}: {'no results' if spec_f.exists() else 'not generated'}")
                continue
            spec = yaml.safe_load(spec_f.read_text())
            tau, cap = thresholds[task]["tau"], budget["max_wall_s"][task]
            best, total_wall, cost, solved, n = None, 0.0, 0.0, 0, 0
            for job in spec["jobs"]:
                d = exp_dir / job["name"]
                rows = _rows(d)
                summ = json.loads((d / "summary.json").read_text()) if (d / "summary.json").exists() else {}
                n += 1
                total_wall += summ.get("wall_s") or (rows[-1]["wall_s"] if rows else 0.0)
                cost += summ.get("cost_usd") or 0.0
                if not rows:
                    continue
                obj, ok, final = objective(rows, tau, cap)
                solved += ok
                if best is None or obj < best["objective"]:
                    best = {"trial": job["name"], "objective": round(obj, 2), "solved": ok, "reward": final,
                            "overrides": job["overrides"]}
            if best is None:
                continue
            tuned_f = CFG / "tuned" / f"{spec['tuning']['algo_file']}_{task}.yaml"
            tuned_f.parent.mkdir(exist_ok=True)
            tuned_f.write_text(yaml.safe_dump({"method": method, "task": task, **best}, sort_keys=False))
            table.append({"method": method, "task": task, "trials": n, "solved": solved, "gpu_hours": total_wall / 3600,
                          "usd": cost, "best_trial": best["trial"], "best_objective_s": best["objective"],
                          "best_solved": best["solved"]})
            print(f"{exp}: best {best['trial']} objective {best['objective']}s (solved={best['solved']}) -> {tuned_f.relative_to(ROOT)}")
    if not table:
        sys.exit("no tuning results found")
    out = gpu_dir / "analysis"
    out.mkdir(exist_ok=True)
    md = ["| task | method | trials | solved | GPU-h | $ | best trial | best objective (s) |", "|---|---|---|---|---|---|---|---|"]
    tex = [r"\begin{tabular}{llrrrrlr}", r"\toprule",
           r"task & method & trials & solved & GPU-h & \$ & best trial & best objective (s) \\", r"\midrule"]
    for t in sorted(table, key=lambda t: (t["task"], t["method"])):
        md.append(f"| {t['task']} | {t['method']} | {t['trials']} | {t['solved']} | {t['gpu_hours']:.2f} | {t['usd']:.2f} | "
                  f"{t['best_trial']} | {t['best_objective_s']:.0f}{'' if t['best_solved'] else ' (unsolved)'} |")
        tex.append(f"{t['task']} & {t['method'].upper()} & {t['trials']} & {t['solved']} & {t['gpu_hours']:.2f} & {t['usd']:.2f} & "
                   f"{t['best_trial'].replace('_', chr(92) + '_')} & {t['best_objective_s']:.0f}{'' if t['best_solved'] else '$^*$'} \\\\")
    tex += [r"\bottomrule", r"\end{tabular}"]
    totals = {}
    for t in table:
        totals.setdefault(t["method"], [0.0, 0.0])
        totals[t["method"]][0] += t["gpu_hours"]
        totals[t["method"]][1] += t["usd"]
    md.append("\nTotal per method: " + ", ".join(f"{m}: {h:.2f} GPU-h (${u:.2f})" for m, (h, u) in totals.items()))
    md.append(f"Budget: {budget['trials']} trials per method and task, seed {budget['seed']}, caps {budget['max_wall_s']} s.")
    (out / "tuning_budget.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    (out / "tuning_budget.tex").write_text("\n".join(tex) + "\n", encoding="utf-8")
    (out / "tuning_budget.json").write_text(json.dumps(table, indent=2))
    print("\n".join(md))
    if paper:
        import shutil

        gen = ROOT / "docs" / "paper" / "generated"
        gen.mkdir(parents=True, exist_ok=True)
        shutil.copy2(out / "tuning_budget.tex", gen / f"{gpu_dir.name}_{paper}_tuning_budget.tex")


def main():
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    p = argparse.ArgumentParser()
    sub = p.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("generate")
    g.add_argument("method", nargs="?")
    g.add_argument("task", nargs="?")
    r = sub.add_parser("report")
    r.add_argument("gpu_dir", type=Path)
    r.add_argument("--paper", metavar="TAG")
    a = p.parse_args()
    budget = yaml.safe_load((CFG / "tuning" / "budget.yaml").read_text())
    if a.cmd == "generate":
        generate([a.method] if a.method else budget["methods"], [a.task] if a.task else budget["tasks"], budget)
    else:
        report(a.gpu_dir, budget, a.paper)


if __name__ == "__main__":
    main()
